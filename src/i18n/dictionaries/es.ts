/**
 * `as const` fija cada texto como tipo literal, lo que impediría que en.ts
 * asignara sus propias cadenas. DeepString conserva la forma del diccionario
 * (y por tanto obliga a traducir todas las claves) relajando los valores a string.
 */
type DeepString<T> = {
  -readonly [K in keyof T]: T[K] extends string ? string : DeepString<T[K]>;
};

